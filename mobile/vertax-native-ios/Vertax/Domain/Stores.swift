// MARK: - App-level stores & router

enum VertaxLocalStore {
    static let testNamespace: String? = {
        #if targetEnvironment(simulator) && DEBUG
        if let token = ProcessInfo.processInfo.environment["VERTAX_TEST_STORE"], UUID(uuidString: token) != nil {
            return token
        }
        #endif
        return nil
    }()

    static let defaults: UserDefaults = {
        if let testNamespace, let suite = UserDefaults(suiteName: "vertax.ui-test.\(testNamespace)") {
            return suite
        }
        return .standard
    }()

    static func load<T: Decodable>(_ type: T.Type, key: String) -> T? {
        guard let data = defaults.data(forKey: key) else { return nil }
        return try? JSONDecoder().decode(type, from: data)
    }

    static func save<T: Encodable>(_ value: T, key: String) {
        guard let data = try? JSONEncoder().encode(value) else { return }
        defaults.set(data, forKey: key)
    }
}

public final class CrateStore: ObservableObject {
    private static let storageKey = "vertax.native.crate.records.v1"
    @Published public var records: [Record] {
        didSet { VertaxLocalStore.save(records, key: Self.storageKey) }
    }

    public init(records: [Record]? = nil) {
        #if DEBUG && targetEnvironment(simulator)
        let fixture = MetadataFixture.crate
        #else
        let fixture: [Record]? = nil
        #endif
        self.records = records
            ?? VertaxLocalStore.load([Record].self, key: Self.storageKey)
            ?? fixture
            ?? []
    }

    public func add(_ r: Record) {
        if !records.contains(where: { $0.id == r.id }) {
            records.insert(r, at: 0)
        }
    }
    public func merge(_ incoming: [Record]) -> Int {
        var ids = Set(records.map(\.id))
        let additions = incoming.filter { ids.insert($0.id).inserted }
        if !additions.isEmpty { records.append(contentsOf: additions) }
        return additions.count
    }
    public func update(_ record: Record) {
        guard let index = records.firstIndex(where: { $0.id == record.id }) else { return }
        records[index] = record
    }

    public func loadDemo() { _ = merge(Record.sample) }
    public func clear() { records = [] }

    /// Filtered + tempo-sorted view used by CrateView.
    public func filtered(query: String, chips: Set<CrateFilter>) -> [Record] {
        var list = records
        let q = query.trimmingCharacters(in: .whitespaces).lowercased()
        if !q.isEmpty {
            list = list.filter {
                "\($0.artist) \($0.title) \($0.label) \($0.catalog) \($0.genre)".lowercased().contains(q)
            }
        }
        // chips of the same KIND are OR'd; different kinds are AND'd
        let byKind = Dictionary(grouping: chips, by: { $0.kind })
        for (_, group) in byKind {
            list = list.filter { rec in group.contains { $0.matches(rec) } }
        }
        return list.sorted { $0.bpm > $1.bpm }
    }
}

public final class SetStore: ObservableObject {
    private static let storageKey = "vertax.native.set.ordered_ids.v1"
    private static let namedSetsKey = "vertax.native.set.library.v1"
    @Published public var orderedIDs: [String] {
        didSet { VertaxLocalStore.save(orderedIDs, key: Self.storageKey) }
    }
    @Published var savedSets: [SavedSet] {
        didSet { VertaxLocalStore.save(savedSets, key: Self.namedSetsKey) }
    }

    public init(orderedIDs: [String]? = nil) {
        self.orderedIDs = orderedIDs
            ?? VertaxLocalStore.load([String].self, key: Self.storageKey)
            ?? []
        savedSets = VertaxLocalStore.load([SavedSet].self, key: Self.namedSetsKey) ?? []
    }

    public func records(in crate: CrateStore) -> [Record] {
        let byID = Dictionary(crate.records.map { ($0.id, $0) }, uniquingKeysWith: { first, _ in first })
        return orderedIDs.compactMap { byID[$0] }
    }
    public func add(_ id: String) { if !orderedIDs.contains(id) { orderedIDs.append(id) } }
    public func remove(_ id: String) { orderedIDs.removeAll { $0 == id } }
    public func move(from: IndexSet, to: Int, in crate: CrateStore) {
        var visibleIDs = records(in: crate).map(\.id)
        visibleIDs.move(fromOffsets: from, toOffset: to)
        orderedIDs = SetPlanner.applyingVisibleOrder(visibleIDs, to: orderedIDs)
    }
    public func clear() { orderedIDs.removeAll() }
    func saveNamed(_ name: String, in crate: CrateStore) {
        let title = name.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !title.isEmpty, !records(in: crate).isEmpty else { return }
        savedSets.insert(SavedSet(id: UUID().uuidString, name: title, createdAt: Date(), entryIDs: orderedIDs), at: 0)
    }

    func rename(_ id: String, to name: String) {
        let title = name.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !title.isEmpty, let index = savedSets.firstIndex(where: { $0.id == id }) else { return }
        savedSets[index].name = title
    }
    func sort(in crate: CrateStore, byCamelot: Bool) {
        orderedIDs = SetPlanner.sortedOrder(orderedIDs, library: crate.records, byCamelot: byCamelot)
    }
    public func autoBuild(from records: [Record], limit: Int = 8) {
        let allowed = records.filter(\.canBuildSet)
        let tracks = allowed.filter { !$0.isRelease }
        let sorted = (tracks.isEmpty ? allowed : tracks).sorted { left, right in
            if (left.bpm > 0) != (right.bpm > 0) { return left.bpm > 0 }
            if left.bpm != right.bpm { return left.bpm < right.bpm }
            return left.keyCode < right.keyCode
        }
        orderedIDs = Array(sorted.prefix(limit).map(\.id))
    }
}

